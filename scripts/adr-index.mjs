#!/usr/bin/env node
// The ADR index, built from the ADR files themselves (ADR 0193), so no change
// edits a shared index file. Every `docs/adr/NNNN-*.md` opens with a frontmatter
// `summary:` line, its decision in force in one line; `docs/adr/retired.md`
// names each number with no file (unused, merged, superseded).
//
//   node scripts/adr-index.mjs [--dir <adr dir>]          prints the index
//   node scripts/adr-index.mjs [--dir <adr dir>] --next   prints the next free number
//   node scripts/adr-index.mjs [--dir <adr dir>] --check  checks the files, prints nothing
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HEADER = `# Architecture decision records

Every ADR number in order, one line each, with the decision in force. Generated by \`pnpm adr:index\` from each ADR's \`summary:\` and \`docs/adr/retired.md\`; never committed. Numbers are never reused: a gap is marked unused, and an ADR merged into another is marked with its new home.
`;

const ADR_FILE = /^(\d{4})-[a-z0-9-]+\.md$/;
const RETIRED_LINE = /^- (\d{4}): (.+)$/;

/** Reads the ADR folder; returns the index lines by number and every problem found. */
function readAdrs(dir) {
  const problems = [];
  const lines = new Map();
  const note = (number, line) => {
    if (lines.has(number)) problems.push(`${number}: two entries share the number`);
    lines.set(number, line);
  };

  for (const file of readdirSync(dir).sort()) {
    const match = ADR_FILE.exec(file);
    if (!match) continue;
    const number = match[1];
    const summary = readSummary(readFileSync(join(dir, file), 'utf8'));
    if (summary === undefined)
      problems.push(`${file}: no frontmatter \`summary:\` line on top of the file`);
    note(number, `- [${number}](${file}) ${summary ?? ''}`.trimEnd());
  }

  for (const [at, line] of readFileSync(join(dir, 'retired.md'), 'utf8').split('\n').entries()) {
    if (!line.startsWith('- ')) continue;
    const match = RETIRED_LINE.exec(line);
    if (!match) {
      problems.push(`retired.md:${at + 1}: not "- NNNN: <fate>."`);
      continue;
    }
    note(match[1], `- ${match[1]}: ${match[2]}`);
  }

  const last = Math.max(0, ...[...lines.keys()].map(Number));
  for (let n = 1; n <= last; n += 1) {
    const number = String(n).padStart(4, '0');
    if (!lines.has(number)) problems.push(`${number}: no ADR file and no line in retired.md`);
  }
  return { lines, problems, next: String(last + 1).padStart(4, '0') };
}

/** The `summary:` of a frontmatter that opens the file, or undefined. */
function readSummary(text) {
  const [first, ...rest] = text.split('\n');
  if (first !== '---') return undefined;
  const end = rest.indexOf('---');
  if (end === -1) return undefined;
  const line = rest.slice(0, end).find((l) => l.startsWith('summary: '));
  const summary = line?.slice('summary: '.length).trim();
  return summary ? summary : undefined;
}

function renderIndex(lines) {
  const ordered = [...lines.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([, l]) => l);
  return `${HEADER}\n${ordered.join('\n')}\n`;
}

function main(argv) {
  const at = argv.indexOf('--dir');
  const dir =
    at === -1 ? fileURLToPath(new URL('../docs/adr/', import.meta.url)) : String(argv[at + 1]);
  const { lines, problems, next } = readAdrs(dir);
  if (problems.length > 0) {
    process.stderr.write(`ADR index: ${problems.length} problem(s)\n${problems.join('\n')}\n`);
    return 1;
  }
  if (argv.includes('--next')) process.stdout.write(`${next}\n`);
  else if (!argv.includes('--check')) process.stdout.write(renderIndex(lines));
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  process.exitCode = main(process.argv.slice(2));
