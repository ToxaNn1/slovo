import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

// The script lives with the other CI scripts; it reads a PR body on stdin.
const script = fileURLToPath(new URL('../../scripts/strip-pr-footer.mjs', import.meta.url));

/** The body the script prints for `body`. */
function strip(body) {
  const run = spawnSync('node', [script], { input: body, encoding: 'utf8' });
  assert.equal(run.status, 0, run.stderr);
  return run.stdout;
}

test('removes the cloud session footer and the blank line before it', () => {
  const body = 'Closes #1.\n\n_Generated by [Claude Code](https://claude.ai/code/session_01AbC)_\n';
  assert.equal(strip(body), 'Closes #1.\n');
});

test('removes the footer with its separator', () => {
  const body =
    'Closes #1.\n\n---\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n';
  assert.equal(strip(body), 'Closes #1.\n');
});

test('removes a plain footer line and keeps Windows line endings', () => {
  const body = 'Summary\r\n\r\nMore text\r\n\r\nGenerated by Claude Code\r\n';
  assert.equal(strip(body), 'Summary\r\n\r\nMore text\r\n');
});

test('leaves a body without the footer as it is', () => {
  const body = 'Summary\n\n---\n\nNotes\n\n';
  assert.equal(strip(body), body);
});

test('leaves any other AI attribution in place', () => {
  const body =
    'Summary\n\nCo-Authored-By: Claude <noreply@anthropic.com>\nWritten with Claude Code, see the log.\n';
  assert.equal(strip(body), body);
});

test('keeps a line that only mentions the footer', () => {
  const body = 'The bot appends _Generated by [Claude Code](https://claude.ai/code)_ to bodies.\n';
  assert.equal(strip(body), body);
});

test('keeps a separator that does not lead to the footer', () => {
  const body = 'Summary\n\n---\n\nNotes\n\n_Generated by [Claude Code](https://claude.ai/code)_';
  assert.equal(strip(body), 'Summary\n\n---\n\nNotes');
});

test('prints nothing for a body that is the footer alone', () => {
  assert.equal(strip('_Generated by [Claude Code](https://claude.ai/code)_'), '');
});
